# 参数设置
chunk_size = 37  # 每行显示的氨基酸数
cmap = "Greens"  # 热图配色
aa_fontsize = 12  # 氨基酸标签字号
pos_fontsize = 14  # 编号字号
fig_width = 20    # 图形总宽度
row_height = 1  # 每行高度（热图+标签）
cbar_width = 0.01 # 颜色条宽度

# 计算分块数
n_chunks = int(np.ceil(num_amino_acids / chunk_size))

# 创建图形
fig = plt.figure(figsize=(fig_width, row_height * n_chunks))
gs = GridSpec(n_chunks, 2, figure=fig, 
             width_ratios=[12, cbar_width*fig_width], 
             wspace=0.05)  # 主图与颜色条的间距

# 计算全局颜色范围
vmin, vmax = np.min(attention_weights), np.max(attention_weights)

# 绘制每行热图

# 绘制每行热图
for i in range(n_chunks):
    start = i * chunk_size
    end = min((i + 1) * chunk_size, num_amino_acids)
    current_chunk_size = end - start
    
    # --- 主热图区域 ---
    ax_main = fig.add_subplot(gs[i, 0])
    
    # 生成热图数据（保持宽度一致）
    heatmap_data = np.full((1, chunk_size), np.nan)
    heatmap_data[0, :current_chunk_size] = attention_weights[start:end]
    
    # 绘制热图
    sns.heatmap(
        heatmap_data,
        cmap=cmap,
        annot=False,
        cbar=False,
        square=True,
        ax=ax_main,
        vmin=vmin,
        vmax=vmax,
        yticklabels=False,
        xticklabels=False
    )
    
    # ===== 新增代码：添加红色边框 =====
    heatmap_matrix = ax_main.collections[0].get_array().reshape(1, -1)
    for y in range(heatmap_data.shape[0]):
        for x in range(heatmap_data.shape[1]):
            if not np.isnan(heatmap_matrix[y, x]) and heatmap_matrix[y, x] > 19.504:
                rect = Rectangle((x, y), 1, 1, 
                               fill=False, 
                               edgecolor='grey', 
                               linewidth=2)
                ax_main.add_patch(rect)
    # ================================
    
    # 添加氨基酸标签（热图下方），并根据条件设置颜色
    for j in range(current_chunk_size):
        aa = amino_acids[start + j]  # 当前氨基酸
        pos = start + j + 1         # 当前位置（1-based）
        
        # 条件判断：哪些标签需要标红（以下示例按位置和氨基酸类型标红）
        if ((pos in range(82,128,1)) or (pos in range(208,333,1))) :  # 示例条件
            color = 'red'
        else:
            color = 'black'
        
        ax_main.text(
            j + 0.5, 1.5,
            aa,
            ha='center',
            va='center',
            fontsize=aa_fontsize,
            color=color  # 设置颜色
        )
    
    # 设置边界
    ax_main.set_xlim(0, chunk_size)
    ax_main.set_ylim(1, 0)  # 扩展y轴空间容纳标签

# 添加全局颜色条
cbar_ax = fig.add_subplot(gs[:, 1])
